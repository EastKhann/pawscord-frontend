def should_skip(value: str) -> bool:
    """Return True if the value should NOT be translated."""
    v = value.strip()
    if not v:
        return True
    # Pure numeric
    if re.match(r'^[\d\s\.,\-\+%:]+$', v):
        return True
    # Single emoji (or just emoji/symbols)
    if re.match(r'^[\U00010000-\U0010FFFF☀-⛿✀-➿\U0001F300-\U0001F9FF\s]+$', v):
        return True
    # Only interpolation variables
    if re.match(r'^(\{\{[^}]+\}\}\s*)+$', v):
        return True
    # URLs
    if re.match(r'^https?://', v):
        return True
    # PawsCord brand
    if 'PawsCord' in v and len(v) < 15:
        return True
    return False

